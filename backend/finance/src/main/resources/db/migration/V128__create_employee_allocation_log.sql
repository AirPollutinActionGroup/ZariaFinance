-- V128: Employee allocation history.
--   One row per event on an allocation — CREATED, ENDED (end date set) or
--   REMOVED (row deleted). The program / project / place names are copied at
--   the time of the event, so the history still reads correctly after an
--   allocation is deleted or a programme is renamed. Rows are only ever added.
CREATE TABLE employee_allocation_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT       NOT NULL REFERENCES employee(id) ON DELETE CASCADE,
    allocation_id   BIGINT       NOT NULL,
    event           VARCHAR(20)  NOT NULL,
    programme_id    BIGINT,
    programme_name  VARCHAR(255),
    project_id      BIGINT,
    project_name    VARCHAR(255),
    role            VARCHAR(255),
    allocation_pct  INTEGER      NOT NULL,
    start_date      DATE,
    end_date        DATE,
    state_names     TEXT,
    city_names      TEXT,
    note            TEXT,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    CONSTRAINT chk_employee_allocation_log_event CHECK (event IN ('CREATED', 'ENDED', 'REMOVED'))
);

CREATE INDEX idx_employee_allocation_log_employee ON employee_allocation_log(employee_id, created_at);

-- Allocations made before this migration get their CREATED event, dated when they were made.
INSERT INTO employee_allocation_log (
    employee_id, allocation_id, event, programme_id, programme_name, project_id, project_name, role,
    allocation_pct, start_date, end_date, state_names, city_names, created_at, updated_at, created_by, updated_by)
SELECT a.employee_id, a.id, 'CREATED', a.programme_id, pg.programme_name, a.project_id, pj.programme_name, a.role,
       a.allocation_pct, a.start_date, a.end_date,
       (SELECT string_agg(s.state_name, ', ' ORDER BY s.state_name)
          FROM employee_allocation_state eas JOIN state_master s ON s.id = eas.state_id
         WHERE eas.employee_allocation_id = a.id),
       (SELECT string_agg(c.city_name, ', ' ORDER BY c.city_name)
          FROM employee_allocation_city eac JOIN city_master c ON c.id = eac.city_id
         WHERE eac.employee_allocation_id = a.id),
       a.created_at, a.created_at, a.created_by, a.created_by
FROM employee_allocation a
LEFT JOIN programme pg ON pg.id = a.programme_id
LEFT JOIN programme pj ON pj.id = a.project_id;
