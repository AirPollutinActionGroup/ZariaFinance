-- V124: Document Type master — manageable list of identity document types a
--       donor can be identified by (PAN Card, Aadhaar Card, Passport ID, …),
--       surfaced under Master Configuration, replacing the hardcoded
--       IdentityDocumentType enum. `code` is the stable identifier that
--       donor_master.document_type already stores (e.g. 'PAN_CARD'); `name`
--       is the label shown on forms.
CREATE TABLE document_type_master (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL UNIQUE,
    name        VARCHAR(255) NOT NULL UNIQUE,
    status      BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(255),
    updated_by  VARCHAR(255)
);

CREATE INDEX idx_document_type_master_status ON document_type_master(status);

-- The six types the enum had, with the same codes, so existing donors keep theirs.
INSERT INTO document_type_master (code, name, status) VALUES
('PAN_CARD', 'PAN Card', true),
('AADHAAR_CARD', 'Aadhaar Card', true),
('VOTER_ID', 'Voter ID', true),
('DRIVING_LICENSE', 'Driving License', true),
('PASSPORT_ID', 'Passport ID', true),
('FOREIGN_TAX_ID', 'Foreign Tax Identification Number', true);
