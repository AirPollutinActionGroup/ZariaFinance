-- V122: Fund suggestion weights — the points a fund earns towards its score
--       when the debit note form suggests funds. One row, edited under Master
--       Configuration → Fund Suggestion; seeded with the shipped defaults.
CREATE TABLE fund_suggestion_weights (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_match           INTEGER NOT NULL,
    covers_amount             INTEGER NOT NULL,
    restricted_for_programme  INTEGER NOT NULL,
    expiry_max                INTEGER NOT NULL,
    has_grant                 INTEGER NOT NULL,
    unrestricted              INTEGER NOT NULL,
    expiry_window_days        INTEGER NOT NULL,
    change_reason             VARCHAR(500),
    created_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by                VARCHAR(255),
    updated_by                VARCHAR(255)
);

