-- V127: Employee banking detail, PAN number, and identity documents.
--   * PAN and the salary bank account are optional columns on employee.
--   * employee_document holds the uploaded PAN Card / Aadhaar Card copies —
--     at most one file of each type per employee (a new upload replaces it).
ALTER TABLE employee ADD COLUMN pan_number          VARCHAR(10);
ALTER TABLE employee ADD COLUMN account_holder_name VARCHAR(255);
ALTER TABLE employee ADD COLUMN bank_name           VARCHAR(255);
ALTER TABLE employee ADD COLUMN account_type        VARCHAR(20);
ALTER TABLE employee ADD COLUMN account_number      VARCHAR(18);
ALTER TABLE employee ADD COLUMN ifsc_code           VARCHAR(11);
ALTER TABLE employee ADD COLUMN branch_name         VARCHAR(255);

ALTER TABLE employee ADD CONSTRAINT chk_employee_account_type
    CHECK (account_type IS NULL OR account_type IN ('Savings', 'Current', 'Salary'));

CREATE TABLE employee_document (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT       NOT NULL REFERENCES employee(id) ON DELETE CASCADE,
    document_type VARCHAR(20)  NOT NULL,
    file_name     VARCHAR(255) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    content       BYTEA        NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by    VARCHAR(255),
    updated_by    VARCHAR(255),
    CONSTRAINT uq_employee_document_type UNIQUE (employee_id, document_type),
    CONSTRAINT chk_employee_document_type CHECK (document_type IN ('PAN_CARD', 'AADHAAR_CARD'))
);
